const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const moduleUnderTest = { exports: {} };
const source = fs.readFileSync(path.join(__dirname, '../src/lib/retriable-resource.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
new Function('module', 'exports', compiled)(moduleUnderTest, moduleUnderTest.exports);
const { createRetriableResource } = moduleUnderTest.exports;
const deferred = () => { let resolve; const promise = new Promise(done => { resolve = done; }); return { promise, resolve }; };
(async () => {
  const old = deferred(); const fresh = deferred(); const applied = [];
  let calls = 0;
  const resource = createRetriableResource(() => (++calls === 1 ? old.promise : fresh.promise), value => applied.push(value), 0);
  const first = resource.load();
  assert.equal(first, resource.load(), 'concurrent requests are deduplicated');
  resource.reset();
  assert.equal(resource.hasLoaded(), false);
  const second = resource.load();
  old.resolve('old-account');
  assert.equal(await first, false);
  assert.deepEqual(applied, [], 'old account responses must never restore private lists');
  assert.equal(second, resource.load(), 'old completion does not clear a newer in-flight request');
  fresh.resolve('new-account');
  assert.equal(await second, true);
  assert.deepEqual(applied, ['new-account']);
  assert.equal(resource.hasLoaded(), true);
  let retries = 0;
  const retry = createRetriableResource(async () => { if (++retries === 1) throw Error('offline'); return ['mix']; }, value => applied.push(value), 0);
  assert.equal(await retry.load(), true);
  assert.equal(retries, 2);
  const denied = createRetriableResource(async () => { throw Error('401'); }, () => { throw Error('must not apply'); }, 0);
  assert.equal(await denied.load(), false);
  assert.equal(denied.hasLoaded(), false);
  console.log('PASS: account isolation, stale responses, request deduplication, retry and authorization failures');
})().catch(error => { console.error(error); process.exitCode = 1; });
