const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.join(__dirname, '../src', file), 'utf8');
const layout = read('app/layout.tsx');
const header = read('components/archive-page-header.tsx');
const shell = read('components/archive-header-shell.tsx');
const about = read('components/about-page.tsx');
const css = read('components/archive-page-header.css');
assert(layout.includes('<ArchiveHeaderShell lang={lang}>{children}</ArchiveHeaderShell>'));
assert(shell.includes('<ArchivePageHeaderView'));
assert(!shell.includes('key={pathname}'),'navigation must not remount header');
assert(header.includes('register?.({ pathname, href:location.pathname + location.search + location.hash, props })'));
assert(header.includes('return register ? null'));
assert(!about.includes('<LanguageSwitcher') && !about.includes('paper-page-avatar'),'About must not render a second identity');
assert(shell.includes("router.push(href, {scroll:false})"));
assert(shell.includes("url.searchParams.set('layout', layout)"),'return keeps the selected view and existing filters');
assert(css.includes('position:fixed;left:3vw;top:28px'));
assert(css.includes('top:20px;width:94vw'));
assert(css.includes(':is(.paper-brand,.header-about-link):hover'));
assert(css.includes(':is(.language-switch-button,.shelf-theme-toggle){transition:color'));
const theme = read('components/shelf-theme.css');
assert(theme.includes("):is(:hover,:focus-visible){color:#f3f3f1!important}"));
const motion = read('components/use-mini-player-layout-motion.ts');
assert(motion.includes('new ResizeObserver(schedule)'));
assert(!motion.includes('width: `${'));
assert(!motion.includes('left:`${'));
console.log('PASS: persistent route-independent header, shared mobile/desktop geometry and hover styling, About return navigation, late-CSS player motion without animated layout');
