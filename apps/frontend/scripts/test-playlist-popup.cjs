const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.join(__dirname, '../src');
const source = fs.readFileSync(path.join(root, 'lib/playlist-popup-position.ts'), 'utf8');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject });
const { placePlaylistPopup, clampPlaylistPopup } = exportsObject;
const right = placePlaylistPopup({left:300,right:600,top:150},320,300,1280,800);
assert.equal(right.x,616);
assert.equal(right.y,150);
assert.equal(placePlaylistPopup({left:850,right:1100,top:150},320,300,1280,800).x,514);
const corner = clampPlaylistPopup(2000,-80,320,300,1280,800);
assert.equal(corner.x,948);
assert.equal(corner.y,12);
assert.equal(clampPlaylistPopup(0,2000,320,300,1280,800).y,488);
const component = fs.readFileSync(path.join(root, 'components/track-actions.tsx'), 'utf8');
assert(component.includes("closest('.track-playlist-menu__title')"));
assert(component.includes('createPortal(popup, document.body)'));
assert(component.includes('!desktopPopup && (sheetDrag || isMobileSheet)'));
assert(component.includes("event.key === 'Escape'"));
console.log('PASS: right-side anchor, left fallback, viewport bounds, title-only desktop drag, portal, Escape and separate mobile sheet');
