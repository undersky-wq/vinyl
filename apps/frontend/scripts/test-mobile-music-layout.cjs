const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = name => fs.readFileSync(path.join(__dirname, '../src/components', name), 'utf8');
const layout = read('music-mobile-layout.css');
assert(layout.startsWith('@media(max-width:700px)'));
assert(layout.includes('body:has(.shelf-mix-detail) .mobile-nav{display:none!important}'));
assert(layout.includes('-webkit-line-clamp:2'));
assert(layout.includes('scrollbar-gutter:stable;padding-right:16px'));
assert(layout.includes('align-self:center;min-height:0;height:auto;margin:0;padding:0'));
const track = read('shelf-mix-track.tsx');
for (const name of ['paper-mix-artist', 'paper-mix-title', 'music-mobile-layout.css']) assert(track.includes(name));
const markers = read('timeline-comment-markers.tsx');
assert(markers.includes('setTappedCommentId'));
assert(markers.includes('aria-expanded='));
assert(markers.includes('onPointerDown={event => event.stopPropagation()}'));
const css = read('timeline-comment-markers.css');
assert(css.includes('28px') && css.includes('44px'));
const archive = read('paper-archive.tsx');
assert(archive.includes("const mobileContextPicker = mixesMode ? 'music'"));
assert(archive.includes('onClick={() => setMobilePicker(mobileContextPicker)}'));
assert(archive.includes('aria-label={mobileContextPickerLabel}'));
console.log('Mobile music layout checks passed');
